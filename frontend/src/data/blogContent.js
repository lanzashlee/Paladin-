export function toSlug(title) {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function getArticleBySlug(slug) {
  return blogArticles.find((post) => toSlug(post.title) === slug);
}
